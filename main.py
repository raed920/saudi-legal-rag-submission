def _parse_rerank_json(text: str) -> list[dict]:
    """Strip markdown fences if present and parse JSON."""
    clean = text.strip()
    if clean.startswith("```"):
        clean = clean.split("```")[1]
        if clean.startswith("json"):
            clean = clean[4:]
    try:
        return json.loads(clean.strip())["rankings"]
    except json.JSONDecodeError as e:
        print(f"   [تحذير] فشل تحليل JSON من المعيد: {e}")
        print(f"   [Debug] النص المُستقبل (أول 500 حرف):\n{clean[:500]}")
        # Fallback: return empty rankings, let caller handle it
        return []

def get_reranked_results(user_query: str, results: dict, context: str = "", selected_files: list = None) -> list[dict]:
    """
    Drop-in replacement for the original get_reranked_results.
    Uses an LCEL chain instead of a raw API call.
    Preserves article metadata for citations.
    Limits articles to 25 to avoid overwhelming the re-ranker.
    Includes file name and article title in articles_text for better re-ranking context.
    """
    if not results["ids"][0]:
        return []

    metadatas = results.get("metadatas", [[]])[0]
    candidates = [
        {
            "original_id": results["ids"][0][i],
            "position": i,
            "text": results["documents"][0][i],
            "article_title": metadatas[i].get("article_title", "") if i < len(metadatas) else "",
            "file_id": metadatas[i].get("File_Name_Id", 0) if i < len(metadatas) else 0,
        }
        for i in range(len(results["ids"][0]))
    ]

    # Limit to top 25 articles to avoid overwhelming the re-ranker
    top_candidates = candidates[:25]
    if len(candidates) > 25:
        print(f"   ⚠️ قصر على أفضل 25 مادة من {len(candidates)} (تجنب إرهاق المعيد)")

    articles_text = "\n".join(
        f"\n[مادة {c['position']} — {_FILE_NAMES.get(c['file_id'], 'غير محدد')}]\n"
        f"العنوان: {c['article_title']}\n{c['text']}"
        for c in top_candidates
    )
    context_section = f"\nالمواد السياقية المرتبطة:\n{context}\n" if context else ""

    if selected_files and len(selected_files) > 1:
        file_names = [_FILE_NAMES.get(f, str(f)) for f in selected_files]
        diversity_instruction = (
            f"تنبيه مهم: يشمل هذا الاستفسار أكثر من نظام قانوني ({' و'.join(file_names)}). "
            f"يجب أن تتضمن قائمة الترتيب النهائية مواد من كل نظام إذا كانت ذات صلة."
        )
    else:
        diversity_instruction = ""

    rerank_chain = rerank_prompt | _rerank_llm | _str_parser | RunnableLambda(_parse_rerank_json)

    rankings = rerank_chain.invoke({
        "user_query": user_query,
        "context_section": context_section,
        "diversity_instruction": diversity_instruction,
        "articles_text": articles_text,
    })

    # If re-ranker failed, return candidates in order
    if not rankings:
        print(f"   ⚠️ فشل المعيد، إرجاع النتائج بالترتيب الأصلي")
        return [
            {
                "الرقم التسلسلي": item["original_id"],
                "المادة": item["text"],
                "عنوان_المادة": item["article_title"],
                "file_id": item["file_id"],
            }
            for item in candidates
        ]

    score_map = {r["index"]: r["score"] for r in rankings}
    reranked = sorted(top_candidates, key=lambda x: score_map.get(x["position"], 0), reverse=True)
    # Add the rest of the candidates (not re-ranked) at the end
    reranked.extend(candidates[25:])
    return [
        {
            "الرقم التسلسلي": item["original_id"],
            "المادة": item["text"],
            "عنوان_المادة": item["article_title"],
            "file_id": item["file_id"],
        }
        for item in reranked
    ]


