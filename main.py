def _parse_classification_json(text: str) -> dict:
    """Parse classification JSON response, handling markdown fences."""
    clean = text.strip()
    if clean.startswith("```"):
        clean = clean.split("```")[1]
        if clean.startswith("json"):
            clean = clean[4:]
    try:
        return json.loads(clean.strip())
    except json.JSONDecodeError:
        # Fallback: extract number from text
        import re
        numbers = re.findall(r'\d+', clean)
        return {
            "primary": numbers[0] if numbers else "1",
            "confidence": "low",
            "alternatives": [],
            "reasoning": "فشل تحليل JSON"
        }


def classify_query_full(user_query: str) -> dict:
    """
    Runs the 4-step hierarchical classification and returns:
      {"القسم": "3", "الباب": "2", "الفصل": "1", "مجموعة_التصنيف": "3"}
    """
    print("🔍 تحديد القسم...")
    qism = classify_qism_chain.invoke({"user_query": user_query}).strip()
    print(f"   ✅ القسم: {qism}")

    print("🔍 تحديد الباب...")
    bab = classify_bab_chain.invoke({"user_query": user_query, "qism": qism}).strip()
    print(f"   ✅ الباب: {bab}")

    print("🔍 تحديد الفصل...")
    fasl = classify_fasl_chain.invoke({"user_query": user_query, "qism": qism, "bab": bab}).strip()
    print(f"   ✅ الفصل: {fasl}")

    print("🔍 تحديد مجموعة التصنيف...")
    majmooa = classify_majmooa_chain.invoke(
        {"user_query": user_query, "qism": qism, "bab": bab, "fasl": fasl}
    ).strip()
    print(f"   ✅ المجموعة: {majmooa}")

    return {"القسم": qism, "الباب": bab, "الفصل": fasl, "مجموعة_التصنيف": majmooa}


def classify_query_full_with_confidence(user_query: str) -> dict:
    """
    Runs the 4-step hierarchical classification WITH confidence scores.
    Returns detailed classification with alternatives for fallback retrieval.
    
    Returns:
      {
        "qism": {"primary": "3", "confidence": "high", "alternatives": [], "reasoning": "..."},
        "bab": {"primary": "1", "confidence": "medium", "alternatives": ["2"], "reasoning": "..."},
        "fasl": {"primary": "4", "confidence": "high", "alternatives": [], "reasoning": "..."},
        "majmooa": {"primary": "1", "confidence": "medium", "alternatives": ["2"], "reasoning": "..."},
        "overall_confidence": "medium"
      }
    """
    print("🔍 تحديد القسم (مع مستوى الثقة)...")
    qism_raw = classify_qism_chain_with_confidence.invoke({"user_query": user_query})
    qism_data = _parse_classification_json(qism_raw)
    print(f"   ✅ القسم: {qism_data['primary']} (ثقة: {qism_data['confidence']})")
    
    qism = str(qism_data["primary"]).strip()

    print("🔍 تحديد الباب (مع مستوى الثقة)...")
    bab_raw = classify_bab_chain_with_confidence.invoke({"user_query": user_query, "qism": qism})
    bab_data = _parse_classification_json(bab_raw)
    print(f"   ✅ الباب: {bab_data['primary']} (ثقة: {bab_data['confidence']})")

    bab = str(bab_data["primary"]).strip()

    print("🔍 تحديد الفصل (مع مستوى الثقة)...")
    fasl_raw = classify_fasl_chain_with_confidence.invoke({"user_query": user_query, "qism": qism, "bab": bab})
    fasl_data = _parse_classification_json(fasl_raw)
    print(f"   ✅ الفصل: {fasl_data['primary']} (ثقة: {fasl_data['confidence']})")

    fasl = str(fasl_data["primary"]).strip()

    print("🔍 تحديد مجموعة التصنيف (مع مستوى الثقة)...")
    majmooa_raw = classify_majmooa_chain_with_confidence.invoke(
        {"user_query": user_query, "qism": qism, "bab": bab, "fasl": fasl}
    )
    majmooa_data = _parse_classification_json(majmooa_raw)
    print(f"   ✅ المجموعة: {majmooa_data['primary']} (ثقة: {majmooa_data['confidence']})")

    # Determine overall confidence (lowest of all levels)
    confidence_order = {"high": 3, "medium": 2, "low": 1}
    confidences = [
        qism_data.get("confidence", "low"),
        bab_data.get("confidence", "low"),
        fasl_data.get("confidence", "low"),
        majmooa_data.get("confidence", "low")
    ]
    min_conf = min(confidences, key=lambda c: confidence_order.get(c, 0))

    return {
        "qism": qism_data,
        "bab": bab_data,
        "fasl": fasl_data,
        "majmooa": majmooa_data,
        "overall_confidence": min_conf
    }


