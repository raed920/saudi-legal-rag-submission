def build_filter(qism: str, bab: str = None, fasl: str = None, majmooa: str = None, strict: bool = True) -> dict:
    """Build ChromaDB filter based on classification levels."""
    conditions = [{"File_Name_Id": {"$eq": 1}}]
    conditions.append({"section_Id": {"$eq": int(qism)}})
    
    if bab is not None:
        conditions.append({"chapter_Id": {"$eq": int(bab)}})
    if fasl is not None:
        conditions.append({"part_Id": {"$eq": int(fasl)}})
    if majmooa is not None and str(majmooa).strip() != "" and strict:
        try:
            conditions.append({"sub_part_Id": {"$eq": int(majmooa)}})
        except (ValueError, TypeError):
            pass  # invalid majmooa value — skip filter, relaxation handles it
    
    return {"$and": conditions}


def retrieve_with_progressive_relaxation(
    query: str, 
    qism: str, 
    bab: str, 
    fasl: str, 
    majmooa: str,
    min_results: int = 5,
    k: int = 10
) -> tuple:
    """
    Retrieve documents with progressive filter relaxation.
    Starts with strict filters and relaxes if not enough results.
    
    Returns: (list of docs, retrieval log)
    """
    retrieval_log = []
    
    # Level 1: Full strict filter
    filter_strict = build_filter(qism, bab, fasl, majmooa, strict=True)
    docs = vectorstore.similarity_search(query=query, k=k, filter=filter_strict)
    retrieval_log.append({"level": "strict", "count": len(docs)})
    print(f"   🔍 بحث صارم: {len(docs)} نتيجة")
    
    if len(docs) >= min_results:
        return docs, retrieval_log
    
    # Level 2: Relax - remove majmooa filter
    filter_without_majmooa = build_filter(qism, bab, fasl, majmooa=None, strict=True)
    docs_relax1 = vectorstore.similarity_search(query=query, k=k, filter=filter_without_majmooa)
    retrieval_log.append({"level": "without_majmooa", "count": len(docs_relax1)})
    print(f"   🔍 بحث بدون مجموعة: {len(docs_relax1)} نتيجة")
    
    # Merge with strict results (deduplicate by content hash)
    all_docs = {hash(doc.page_content): doc for doc in docs}
    for doc in docs_relax1:
        doc_hash = hash(doc.page_content)
        if doc_hash not in all_docs:
            all_docs[doc_hash] = doc
    
    if len(all_docs) >= min_results:
        return list(all_docs.values()), retrieval_log
    
    # Level 3: Relax - remove fasl filter
    filter_without_fasl = build_filter(qism, bab, fasl=None, majmooa=None, strict=False)
    docs_relax2 = vectorstore.similarity_search(query=query, k=k, filter=filter_without_fasl)
    retrieval_log.append({"level": "without_fasl", "count": len(docs_relax2)})
    print(f"   🔍 بحث بدون فصل: {len(docs_relax2)} نتيجة")
    
    for doc in docs_relax2:
        doc_hash = hash(doc.page_content)
        if doc_hash not in all_docs:
            all_docs[doc_hash] = doc
    
    return list(all_docs.values()), retrieval_log

